/** Maximum evaluated turns accepted per report request (10 main + up to 30 follow-ups). */
const MAX_TURNS = 40;
/** Maximum characters allowed per question text. */
const MAX_QUESTION_LENGTH = 1000;
/** Maximum characters allowed per answer text. */
const MAX_ANSWER_LENGTH = 5000;
/** Minimum turns required to generate a meaningful report. */
const MIN_TURNS = 1;

// ─────────────────────────────────────────────────────────────────────────────
// Input types — mirrors EvaluationFeedback and InterviewTurn from src/lib/questions.ts
// Redefined here to keep the API route self-contained and avoid client-module
// imports from server-only code.
// ─────────────────────────────────────────────────────────────────────────────

interface TurnFeedbackInput {
  score: number;
  relevance: string;
  bankingKnowledge: string;
  strengths: string[];
  improvements: string[];
  suggestedAnswer: string;
  followUpQuestion: string;
}

interface TurnInput {
  turnId: string;
  category: string;
  question: string;
  isFollowUp: boolean;
  mainQuestionId?: string;
  answer: string;
  feedback: TurnFeedbackInput;
}

// ─────────────────────────────────────────────────────────────────────────────
// Output types
// ─────────────────────────────────────────────────────────────────────────────

interface CategoryBreakdown {
  category: string;
  /** Average per-question score (1–10 scale). */
  averageScore: number;
  /** Number of evaluated turns (main + follow-ups) in this category. */
  turnCount: number;
  /** Short qualitative assessment generated by Gemini. */
  assessment: string;
}

interface AnswerImprovement {
  question: string;
  /** Concise improvement suggestion generated by Gemini. */
  suggestion: string;
}

interface InterviewReport {
  /**
   * Completion-weighted overall score (0–100) following SBI PO exam style:
   * Each of the 10 main questions carries up to 10 points (total 100).
   * Unanswered/skipped questions contribute 0 points.
   * If follow-ups were evaluated, the effective main question score incorporates them.
   */
  overallScore: number;
  /** Number of main questions answered out of totalSessionQuestions. */
  answeredCount: number;
  /** Total main questions in the mock session (standard: 10). */
  totalSessionQuestions: number;
  /** Percentage of interview completed (e.g. 10% for 1/10). */
  completionRate: number;
  /** Average answer quality percentage on answered questions alone (e.g. 90%). */
  answerQualityRate: number;
  overallAssessment: string;
  categoryBreakdown: CategoryBreakdown[];
  strengths: string[];
  improvementAreas: string[];
  priorityTopics: string[];
  answerImprovements: AnswerImprovement[];
  /**
   * Cautious guidance about current preparation level.
   * Always includes the mandatory disclaimer that this is AI practice
   * feedback and cannot predict the actual SBI PO interview result.
   */
  readinessAssessment: string;
}

