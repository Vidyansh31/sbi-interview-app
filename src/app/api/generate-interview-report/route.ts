/**
 * Builds the Gemini prompt for qualitative narrative generation.
 * Scores and category averages are pre-computed and provided so Gemini
 * cannot fabricate numerical values.
 */
function buildNarrativePrompt(
  turns: TurnInput[],
  metrics: SessionScoreMetrics,
  categoryStats: Map<string, { totalScore: number; count: number }>
): string {
  // Serialise the turn digest — trim answer to 500 chars to keep prompt concise
  const turnDigest = turns
    .map((t, i) => {
      const label = t.isFollowUp ? `Follow-Up (${t.category})` : `Main Q${i + 1} (${t.category})`;
      return (
        `[Turn ${i + 1} — ${label}]\n` +
        `Q: ${t.question}\n` +
        `A (trimmed): ${t.answer.slice(0, 500)}${t.answer.length > 500 ? "…" : ""}\n` +
        `Score: ${t.feedback.score}/10 | Strengths: ${t.feedback.strengths.join("; ")} | Improvements: ${t.feedback.improvements.join("; ")}`
      );
    })
    .join("\n\n");

  // Serialise category stats
  const categoryStatsText = Array.from(categoryStats.entries())
    .map(([cat, stats]) => {
      const avg = (stats.totalScore / stats.count).toFixed(2);
      return `- ${cat}: avg ${avg}/10 over ${stats.count} turn(s)`;
    })
    .join("\n");

  // Select up to 5 weakest turns (lowest score) for targeted answer improvement suggestions
  const weakestTurns = [...turns]
    .sort((a, b) => a.feedback.score - b.feedback.score)
    .slice(0, 5);

  const weakestTurnsText = weakestTurns
    .map((t) => `Q: "${t.question.slice(0, 200)}"`)
    .join("\n");

  return `You are a senior, experienced SBI (State Bank of India) Probationary Officer interview board evaluator writing a final performance report for a mock interview candidate.

Below are the candidate's evaluated interview turns, pre-computed scores, and category statistics.

IMPORTANT — DO NOT invent or change any numerical scores. All scores have already been calculated deterministically. Your task is ONLY to provide qualitative narrative insights based on the evidence below.

SESSION METRICS:
- Overall Exam Score (Completion-Weighted): ${metrics.overallScore} / 100
- Main Questions Answered: ${metrics.answeredCount} of ${metrics.totalSessionQuestions} (${metrics.completionRate}% completion)
- Average Answer Quality on Attempted Questions: ${metrics.answerQualityRate}%
${metrics.answeredCount < metrics.totalSessionQuestions ? `NOTE: The candidate only completed ${metrics.answeredCount} of ${metrics.totalSessionQuestions} questions. Highlight this in the overall assessment and readiness assessment as an incomplete attempt.` : ""}

CATEGORY STATISTICS (averages are pre-computed; do NOT alter them):
${categoryStatsText}

FULL TURN DIGEST:
${turnDigest}

WEAKEST TURNS (for answer improvement suggestions):
${weakestTurnsText}

MANDATORY DISCLAIMER to include verbatim in readinessAssessment:
"This score is AI-generated practice feedback. It does not represent an official assessment and cannot predict your actual SBI PO interview result."

TASK: Return ONLY a single valid JSON object conforming exactly to this schema. Do NOT include Markdown fences, commentary, or any text outside the JSON object.

{
  "overallAssessment": "<2–4 sentence summary of the candidate's overall interview performance, referencing specific patterns observed across their answers and noting completion level>",
  "categoryAssessments": {
    "<CategoryName1>": "<1–2 sentence assessment specific to the candidate's answers in this category>",
    "<CategoryName2>": "<1–2 sentence assessment>"
  },
  "strengths": [
    "<Specific strength grounded in an actual answer — not generic praise>",
    "<Another specific strength>"
  ],
  "improvementAreas": [
    "<Specific weakness observed in candidate's answers with actionable improvement advice>",
    "<Another specific weakness>"
  ],
  "priorityTopics": [
    "<Practical revision topic for SBI PO preparation based on the candidate's weaknesses>",
    "<Another revision topic>"
  ],
  "answerImprovements": [
    {
      "question": "<Exact or near-exact question text from the session>",
      "suggestion": "<Concise, specific advice to improve the candidate's actual answer to this question>"
    }
  ],
  "readinessAssessment": "<2–3 sentence cautious readiness guidance. MUST include the mandatory disclaimer verbatim.>"
}

Rules:
- categoryAssessments must include an entry for EVERY category listed in the category statistics above. Use the exact category name as the key.
- strengths and improvementAreas: minimum 2 items each, maximum 5 items each.
- priorityTopics: minimum 2 items, maximum 5 items.
- answerImprovements: provide suggestions for the weakest turns listed above. Minimum 1 item, maximum 5 items.
- Do NOT repeat the mandatory disclaimer anywhere except in readinessAssessment.
- Do NOT fabricate candidate details, credentials, or scores not shown above.
- Write in a professional, constructive, and encouraging tone appropriate for an SBI PO mock interview coach.`;
}

// ─────────────────────────────────────────────────────────────────────────────
// Route handler
// ─────────────────────────────────────────────────────────────────────────────

export async function POST(request: Request) {
  try {
    // 1. Parse request body
    let body: unknown;
    try {
      body = await request.json();
    } catch {
      return NextResponse.json(
        { error: "Invalid JSON in request body." },
        { status: 400 }
      );
    }

    // 2. Validate turns array
    const turnsRaw = (body as Record<string, unknown>)?.turns;
    const validationResult = validateTurns(turnsRaw);
    if (!validationResult.ok) {
      return NextResponse.json(
        { error: validationResult.error },
        { status: 400 }
      );
    }
    const turns = validationResult.turns;

    // 3. Compute scores deterministically (server-side — NOT delegated to Gemini)
    // Option A: Completion-Weighted SBI PO Exam Style
    const metrics = computeScoreMetrics(turns, 10);
    const categoryStats = computeCategoryStats(turns);

    // 4. Verify Gemini API key
    const apiKey = process.env.GEMINI_API_KEY;
    if (!apiKey) {
      return NextResponse.json(
        { error: "Gemini API is not configured." },
        { status: 500 }
      );
    }

    const ai = new GoogleGenAI({ apiKey });

    // 5. Build prompt and call Gemini for qualitative narrative
    const prompt = buildNarrativePrompt(turns, metrics, categoryStats);

    const firstResponse = await ai.models.generateContent({
      model: "gemini-3.5-flash-lite",
      contents: prompt,
      config: {
        responseMimeType: "application/json",
      },
    });

    let narrativeResult = parseNarrative(firstResponse.text);

    // 6. Single retry with a tighter prompt if first attempt fails validation
    if (!narrativeResult.success) {
      console.warn(
        "First Gemini report narrative attempt failed validation:",
        narrativeResult.reason,
        "— Retrying once."
      );

      const retryPrompt = `You are an automated JSON formatter for interview reports.
Return ONLY valid JSON conforming to the schema below. No markdown, no prose outside the JSON.

SCHEMA:
{
  "overallAssessment": "string",
  "categoryAssessments": { "CategoryName": "string" },
  "strengths": ["string"],
  "improvementAreas": ["string"],
  "priorityTopics": ["string"],
  "answerImprovements": [{ "question": "string", "suggestion": "string" }],
  "readinessAssessment": "string (must include: This score is AI-generated practice feedback. It does not represent an official assessment and cannot predict your actual SBI PO interview result.)"
}

SESSION CONTEXT:
- Overall Score: ${metrics.overallScore}/100
- Answered: ${metrics.answeredCount} of ${metrics.totalSessionQuestions} questions (${metrics.completionRate}% completion)
- Quality Rate: ${metrics.answerQualityRate}%
- Categories: ${Array.from(categoryStats.keys()).join(", ")}

Provide a concise but helpful interview performance report. Minimum 2 strengths, 2 improvement areas, 2 priority topics, 1 answer improvement. Include every category from the list above in categoryAssessments.`;

      const retryResponse = await ai.models.generateContent({
        model: "gemini-3.5-flash-lite",
        contents: retryPrompt,
        config: {
          responseMimeType: "application/json",
        },
      });

      narrativeResult = parseNarrative(retryResponse.text);

      if (!narrativeResult.success) {
        console.error("Gemini report narrative retry also failed validation:", {
          reason: narrativeResult.reason,
          rawLength: retryResponse.text ? retryResponse.text.length : 0,
        });
        return NextResponse.json(
          {
            error:
              "Unable to generate the interview report due to an unexpected evaluator response. Please try again.",
          },
          { status: 502 }
        );
      }
    }

    // 7. Assemble the final report, merging deterministic scores with Gemini narrative
    const narrative = narrativeResult.data;

    const categoryBreakdown: CategoryBreakdown[] = Array.from(
      categoryStats.entries()
    ).map(([cat, stats]) => ({
      category: cat,
      averageScore: parseFloat((stats.totalScore / stats.count).toFixed(2)),
      turnCount: stats.count,
      assessment: narrative.categoryAssessments[cat] ?? "No assessment available for this category.",
    }));

    const report: InterviewReport = {
      overallScore: metrics.overallScore,
      answeredCount: metrics.answeredCount,
      totalSessionQuestions: metrics.totalSessionQuestions,
      completionRate: metrics.completionRate,
      answerQualityRate: metrics.answerQualityRate,
      overallAssessment: narrative.overallAssessment,
      categoryBreakdown,
      strengths: narrative.strengths,
      improvementAreas: narrative.improvementAreas,
      priorityTopics: narrative.priorityTopics,
      answerImprovements: narrative.answerImprovements,
      readinessAssessment: narrative.readinessAssessment,
    };

    return NextResponse.json({ success: true, report });
  } catch (error) {
    // Never expose stack traces, API keys, or internal error details
    console.error(
      "Interview report generation failed:",
      error instanceof Error ? error.message : "Unknown error"
    );
    return NextResponse.json(
      { error: "Unable to generate the interview report. Please try again." },
      { status: 502 }
    );
  }
}
