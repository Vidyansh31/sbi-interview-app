/**
 * Validates a single feedback object from a submitted turn.
 * Returns a reason string on failure, or null on success.
 */
function validateTurnFeedback(fb: unknown, turnIndex: number): string | null {
  if (!fb || typeof fb !== "object" || Array.isArray(fb)) {
    return `Turn ${turnIndex}: feedback must be an object`;
  }
  const f = fb as Record<string, unknown>;

  if (
    typeof f.score !== "number" ||
    !Number.isInteger(f.score) ||
    f.score < 1 ||
    f.score > 10
  ) {
    return `Turn ${turnIndex}: feedback.score must be an integer from 1 to 10, got ${JSON.stringify(f.score)}`;
  }
  if (typeof f.relevance !== "string" || !f.relevance.trim()) {
    return `Turn ${turnIndex}: feedback.relevance must be a non-empty string`;
  }
  if (typeof f.bankingKnowledge !== "string" || !f.bankingKnowledge.trim()) {
    return `Turn ${turnIndex}: feedback.bankingKnowledge must be a non-empty string`;
  }
  if (
    !Array.isArray(f.strengths) ||
    f.strengths.length === 0 ||
    !(f.strengths as unknown[]).every(
      (s) => typeof s === "string" && (s as string).trim()
    )
  ) {
    return `Turn ${turnIndex}: feedback.strengths must be a non-empty array of strings`;
  }
  if (
    !Array.isArray(f.improvements) ||
    f.improvements.length === 0 ||
    !(f.improvements as unknown[]).every(
      (s) => typeof s === "string" && (s as string).trim()
    )
  ) {
    return `Turn ${turnIndex}: feedback.improvements must be a non-empty array of strings`;
  }
  if (typeof f.suggestedAnswer !== "string" || !f.suggestedAnswer.trim()) {
    return `Turn ${turnIndex}: feedback.suggestedAnswer must be a non-empty string`;
  }
  if (typeof f.followUpQuestion !== "string") {
    return `Turn ${turnIndex}: feedback.followUpQuestion must be a string`;
  }
  return null;
}

/**
 * Validates and normalises the array of submitted turns.
 * Returns either a validated array or an error message.
 */
function validateTurns(
  raw: unknown
): { ok: true; turns: TurnInput[] } | { ok: false; error: string } {
  if (!Array.isArray(raw)) {
    return { ok: false, error: "turns must be a non-empty array" };
  }
  if (raw.length < MIN_TURNS) {
    return { ok: false, error: `At least ${MIN_TURNS} evaluated turn is required` };
  }
  if (raw.length > MAX_TURNS) {
    return {
      ok: false,
      error: `Too many turns submitted. Maximum allowed is ${MAX_TURNS}`,
    };
  }

  const turns: TurnInput[] = [];

  for (let i = 0; i < raw.length; i++) {
    const t = raw[i] as Record<string, unknown>;

    if (!t || typeof t !== "object" || Array.isArray(t)) {
      return { ok: false, error: `Turn ${i}: must be an object` };
    }

    // turnId
    if (typeof t.turnId !== "string" || !t.turnId.trim()) {
      return { ok: false, error: `Turn ${i}: turnId must be a non-empty string` };
    }

    // category
    if (typeof t.category !== "string" || !t.category.trim()) {
      return { ok: false, error: `Turn ${i}: category must be a non-empty string` };
    }

    // question
    if (typeof t.question !== "string" || !t.question.trim()) {
      return { ok: false, error: `Turn ${i}: question must be a non-empty string` };
    }
    if (t.question.length > MAX_QUESTION_LENGTH) {
      return {
        ok: false,
        error: `Turn ${i}: question exceeds maximum length of ${MAX_QUESTION_LENGTH} characters`,
      };
    }

    // isFollowUp
    if (typeof t.isFollowUp !== "boolean") {
      return { ok: false, error: `Turn ${i}: isFollowUp must be a boolean` };
    }

    // answer
    if (typeof t.answer !== "string" || !t.answer.trim()) {
      return { ok: false, error: `Turn ${i}: answer must be a non-empty string` };
    }
    if (t.answer.length > MAX_ANSWER_LENGTH) {
      return {
        ok: false,
        error: `Turn ${i}: answer exceeds maximum length of ${MAX_ANSWER_LENGTH} characters`,
      };
    }

    // feedback (must be present and valid — unevaluated turns are not accepted)
    const feedbackError = validateTurnFeedback(t.feedback, i);
    if (feedbackError) {
      return { ok: false, error: feedbackError };
    }

    const fb = t.feedback as Record<string, unknown>;
    const mainQuestionId = typeof t.mainQuestionId === "string" && t.mainQuestionId.trim()
      ? t.mainQuestionId.trim()
      : undefined;

    turns.push({
      turnId: (t.turnId as string).trim(),
      category: (t.category as string).trim(),
      question: (t.question as string).trim(),
      isFollowUp: t.isFollowUp as boolean,
      mainQuestionId,
      answer: (t.answer as string).trim(),
      feedback: {
        score: fb.score as number,
        relevance: (fb.relevance as string).trim(),
        bankingKnowledge: (fb.bankingKnowledge as string).trim(),
        strengths: (fb.strengths as string[]).map((s) => s.trim()),
        improvements: (fb.improvements as string[]).map((s) => s.trim()),
        suggestedAnswer: (fb.suggestedAnswer as string).trim(),
        followUpQuestion: (fb.followUpQuestion as string).trim(),
      },
    });
  }

  return { ok: true, turns };
}

// ─────────────────────────────────────────────────────────────────────────────
// Deterministic score calculations (server-side, not delegated to Gemini)
// ─────────────────────────────────────────────────────────────────────────────

interface SessionScoreMetrics {
  overallScore: number;
  answeredCount: number;
  totalSessionQuestions: number;
  completionRate: number;
  answerQualityRate: number;
}

/**
 * Calculates Option A (Completion-Weighted / SBI PO Exam Style):
 * - Total mock interview consists of `totalSessionQuestions` (default: 10).
 * - Each main question answered carries up to 10 points (total possible = 100).
 * - If a main question has follow-up questions, the composite score for that main topic
 *   is the average of the main turn and its follow-ups (each 1-10).
 * - Unanswered / skipped questions contribute 0 points.
 * - answerQualityRate: Average percentage score earned on the questions actually answered (0-100%).
 * - overallScore: Total earned points out of 100 = sum(topicScores).
 */
function computeScoreMetrics(
  turns: TurnInput[],
  totalSessionQuestions: number = 10
): SessionScoreMetrics {
  if (turns.length === 0) {
    return {
      overallScore: 0,
      answeredCount: 0,
      totalSessionQuestions,
      completionRate: 0,
      answerQualityRate: 0,
    };
  }

  // Group turns by main question topic (fallback to category/question sequence)
  const topicMap = new Map<string, number[]>();
  for (let i = 0; i < turns.length; i++) {
    const t = turns[i];
    // Use main question ID grouping if available, or cluster by category/sequence
    const topicKey = t.mainQuestionId
      ? t.mainQuestionId
      : (t.isFollowUp ? `topic-followup-${i}` : `topic-main-${t.category}-${t.question.slice(0, 30)}`);
    
    const existing = topicMap.get(topicKey) ?? [];
    existing.push(t.feedback.score);
    topicMap.set(topicKey, existing);
  }

  // Calculate score earned per main question topic (scaled 0–10)
  const topicScores: number[] = [];
  for (const scores of topicMap.values()) {
    const topicAvg = scores.reduce((a, b) => a + b, 0) / scores.length;
    topicScores.push(topicAvg);
  }

  const answeredCount = Math.min(topicScores.length, totalSessionQuestions);
  // Total earned points: each answered question topic gives up to 10 points
  const totalEarnedPoints = topicScores.reduce((sum, score) => sum + score, 0);
  const overallScore = Math.min(100, Math.round(totalEarnedPoints));

  // Average quality on answered questions: (avgTopicScore / 10) * 100
  const avgQuality = answeredCount > 0 ? (totalEarnedPoints / answeredCount) : 0;
  const answerQualityRate = Math.round((avgQuality / 10) * 100);
  const completionRate = Math.round((answeredCount / totalSessionQuestions) * 100);

  return {
    overallScore,
    answeredCount,
    totalSessionQuestions,
    completionRate,
    answerQualityRate,
  };
}

/**
 * Builds a per-category summary with deterministic averages.
 * Each category's average score is on the 1–10 scale (not normalised) so
 * Gemini can reference it in qualitative assessments.
 */
function computeCategoryStats(
  turns: TurnInput[]
): Map<string, { totalScore: number; count: number }> {
  const map = new Map<string, { totalScore: number; count: number }>();
  for (const turn of turns) {
    const entry = map.get(turn.category) ?? { totalScore: 0, count: 0 };
    entry.totalScore += turn.feedback.score;
    entry.count += 1;
    map.set(turn.category, entry);
  }
  return map;
}

// ─────────────────────────────────────────────────────────────────────────────
// Gemini output parsing helpers (mirrors patterns in evaluate-answer/route.ts)
// ─────────────────────────────────────────────────────────────────────────────

function cleanJsonText(raw: string): string {
  let text = raw.trim();
  if (text.startsWith("```")) {
    text = text.replace(/^```(?:json)?\s*/i, "");
    text = text.replace(/\s*```$/, "");
  }
  return text.trim();
}

interface RawReportNarrative {
  overallAssessment: string;
  categoryAssessments: Record<string, string>;
  strengths: string[];
  improvementAreas: string[];
  priorityTopics: string[];
  answerImprovements: Array<{ question: string; suggestion: string }>;
  readinessAssessment: string;
}

/**
 * Validates Gemini's qualitative narrative output.
 * Scores are NOT validated here — they are computed deterministically above.
 */
function validateNarrative(
  obj: unknown
): { valid: true; data: RawReportNarrative } | { valid: false; reason: string } {
  if (!obj || typeof obj !== "object" || Array.isArray(obj)) {
    return { valid: false, reason: "Narrative is not a JSON object" };
  }
  const r = obj as Record<string, unknown>;

  if (typeof r.overallAssessment !== "string" || !r.overallAssessment.trim()) {
    return { valid: false, reason: "overallAssessment must be a non-empty string" };
  }
  if (!r.categoryAssessments || typeof r.categoryAssessments !== "object" || Array.isArray(r.categoryAssessments)) {
    return { valid: false, reason: "categoryAssessments must be an object" };
  }
  const catAssessments = r.categoryAssessments as Record<string, unknown>;
  for (const [key, val] of Object.entries(catAssessments)) {
    if (typeof val !== "string" || !(val as string).trim()) {
      return { valid: false, reason: `categoryAssessments["${key}"] must be a non-empty string` };
    }
  }
  if (
    !Array.isArray(r.strengths) ||
    r.strengths.length === 0 ||
    !(r.strengths as unknown[]).every((s) => typeof s === "string" && (s as string).trim())
  ) {
    return { valid: false, reason: "strengths must be a non-empty array of strings" };
  }
  if (
    !Array.isArray(r.improvementAreas) ||
    r.improvementAreas.length === 0 ||
    !(r.improvementAreas as unknown[]).every((s) => typeof s === "string" && (s as string).trim())
  ) {
    return { valid: false, reason: "improvementAreas must be a non-empty array of strings" };
  }
  if (
    !Array.isArray(r.priorityTopics) ||
    r.priorityTopics.length === 0 ||
    !(r.priorityTopics as unknown[]).every((s) => typeof s === "string" && (s as string).trim())
  ) {
    return { valid: false, reason: "priorityTopics must be a non-empty array of strings" };
  }
  if (!Array.isArray(r.answerImprovements)) {
    return { valid: false, reason: "answerImprovements must be an array" };
  }
  for (let i = 0; i < (r.answerImprovements as unknown[]).length; i++) {
    const item = (r.answerImprovements as unknown[])[i];
    if (!item || typeof item !== "object" || Array.isArray(item)) {
      return { valid: false, reason: `answerImprovements[${i}] must be an object` };
    }
    const ai = item as Record<string, unknown>;
    if (typeof ai.question !== "string" || !(ai.question as string).trim()) {
      return { valid: false, reason: `answerImprovements[${i}].question must be a non-empty string` };
    }
    if (typeof ai.suggestion !== "string" || !(ai.suggestion as string).trim()) {
      return { valid: false, reason: `answerImprovements[${i}].suggestion must be a non-empty string` };
    }
  }
  if (typeof r.readinessAssessment !== "string" || !r.readinessAssessment.trim()) {
    return { valid: false, reason: "readinessAssessment must be a non-empty string" };
  }

  return {
    valid: true,
    data: {
      overallAssessment: (r.overallAssessment as string).trim(),
      categoryAssessments: Object.fromEntries(
        Object.entries(catAssessments).map(([k, v]) => [k, (v as string).trim()])
      ),
      strengths: (r.strengths as string[]).map((s) => s.trim()),
      improvementAreas: (r.improvementAreas as string[]).map((s) => s.trim()),
      priorityTopics: (r.priorityTopics as string[]).map((s) => s.trim()),
      answerImprovements: (r.answerImprovements as Array<{ question: string; suggestion: string }>).map(
        (item) => ({
          question: item.question.trim(),
          suggestion: item.suggestion.trim(),
        })
      ),
      readinessAssessment: (r.readinessAssessment as string).trim(),
    },
  };
}

function parseNarrative(
  rawText: string | undefined
): { success: true; data: RawReportNarrative } | { success: false; reason: string } {
  if (!rawText || !rawText.trim()) {
    return { success: false, reason: "Gemini returned an empty response" };
  }
  const cleaned = cleanJsonText(rawText);
  let parsed: unknown;
  try {
    parsed = JSON.parse(cleaned);
  } catch (err) {
    return {
      success: false,
      reason: `JSON parse error: ${err instanceof Error ? err.message : String(err)}`,
    };
  }
  const validation = validateNarrative(parsed);
  if (!validation.valid) {
    return { success: false, reason: validation.reason };
  }
  return { success: true, data: validation.data };
}

